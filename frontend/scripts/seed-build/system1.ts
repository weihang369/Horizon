// The shared System 1 fixture (docs/ai/13 W1; demo-data "The System 1 fixture is generated and checked").
// One row template per question-bank entry, generated from backend/horizon/ai/questions/*.json, so the scripted
// backend and the MockClient show the same fixed rows the live `agent`/`naive` paths would write. The caller fills
// `answer` (and `about`) from what actually happened, so a row is fixed but true. seed:check fails when a bank label
// or version changes without a rebuild.
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const BANK_DIR = path.resolve(here, "../../../backend/horizon/ai/questions");

interface BankEntry {
  id: string; version: number; purpose: string; type: "choice" | "noul" | "score"; label: string;
  floor?: number | null; thresholds?: Record<string, number>;
}

export interface System1FixtureRow {
  purpose: string; id: string; version: number; label: string;
  p: number; confidence?: number;
  compared: { name: string; value: number; threshold: number }[];
  result: "used" | "shown_only"; action?: string;
}

/** The scripted value every fixture row shows: a fixed, believable probability (never presented as measured). */
const P = 0.72;
const ACTION: Record<string, string> = {
  route: "answers first", emotion_reply: "shown", emotion_greeting: "shown",   // M9: turn-plan-emotion D13
  // M10 (group-watch D22): who speaks, the steer and the watch faces
  who_first: "answers first", who_second: "speaks second", who_next: "speaks next", who_scene: "speaks next",
  talk_finished: "no steer", emotion_line: "shown", emotion_opening: "shown",
};

export function system1Fixture(dir: string = BANK_DIR): { note: string; rows: Record<string, System1FixtureRow> } {
  const rows: Record<string, System1FixtureRow> = {};
  const files = readdirSync(dir).filter((f) => f.endsWith(".json") && !f.startsWith("_") && f !== "questions.lock.json").sort();
  for (const f of files) {
    const e = JSON.parse(readFileSync(path.join(dir, f), "utf8")) as BankEntry;
    if (e.purpose === "eval_judge") continue;   // persona-context D26: evaluation-only, never asked in a turn (W1)
    if (e.purpose === "reaction") continue;     // turn-plan-emotion D18: a listener reaction has no System 1 row
    const compared: System1FixtureRow["compared"] = [];
    if (e.floor !== undefined && e.floor !== null) compared.push({ name: "confidence", value: P, threshold: e.floor });
    for (const [name, threshold] of Object.entries(e.thresholds ?? {}).sort(([a], [b]) => (a < b ? -1 : 1))) {
      compared.push({ name, value: P, threshold });
    }
    // doc 13 W2 (turn-plan-emotion D23): the face check is display only: p for the face shown, no action
    rows[e.id] = e.purpose === "face_check"
      ? { purpose: e.purpose, id: e.id, version: e.version, label: e.label, p: P, compared, result: "shown_only" }
      : {
        purpose: e.purpose, id: e.id, version: e.version, label: e.label, p: P,
        ...(e.type === "noul" ? {} : { confidence: P }),
        compared, result: "used", action: ACTION[e.id] ?? "used",
      };
  }
  return {
    note: "Generated by seed-build from backend/horizon/ai/questions. Scripted rows: fixed values, the answer filled from what happened.",
    rows,
  };
}
