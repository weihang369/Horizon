"""M13's labelled facts (memory design D40; written blind under evals/reviews/m13-review.md, before any Jev answer).

One row per fact Kai (the user, the You card in both seed worlds) tells a character. Every M13 decision set and the
memory suite's probes are built from these rows, so each label follows from how the item is made:
- `said`: Kai's line in the conversation;
- `memory`: the line the character would keep (two or more details);
- `extend`: a faithful rewrite (every still-true part kept, one detail added);
- `lossy`: a rewrite that drops or blurs a detail the conversation didn't change;
- `probe`: a later message that needs the fact and doesn't state it;
- `level`: how much it matters later (importance, 1–5);
- `reword` / `lossy2` (optional): a faithful paraphrase, and a second lossy version.
"""

